import assert from 'node:assert/strict';
import {deck,assetReturns,scenarioFor,catalog,model} from '../lib/scenario-engine.mjs';
import {assets,presets,initialMarket,applyMarketDay,validateWeights} from '../public/markets.mjs';
const close=(a,b)=>assert.ok(Math.abs(a-b)<1e-8,`${a} != ${b}`);
const zero={growth:0,inflation:0,ratesBps:0,riskBps:0,earnings:0,property:0};
assert.equal(assetReturns({...zero,ratesBps:25}).bonds<assetReturns(zero).bonds,true);
assert.equal(assetReturns({...zero,ratesBps:-25}).bonds>assetReturns(zero).bonds,true);
assert.equal(assetReturns({...zero,ratesBps:25}).property<assetReturns(zero).property,true);
assert.equal(assetReturns({...zero,earnings:-1}).equity<assetReturns(zero).equity,true);
assert.equal(assetReturns({...zero,property:1}).property>assetReturns(zero).property,true);
assert.equal(assetReturns(zero).cash,model.cashCarryPct);
assert.equal(new Set(deck.map(d=>d.id)).size,22);
for(const d of deck){const e=scenarioFor({day:1,scenarioId:d.id});assert.ok(Object.values(e.returns).every(n=>Number.isFinite(n)&&Math.abs(n)<=8));}
assert.ok(scenarioFor({day:1,scenarioId:'hot-inflation'}).returns.bonds<0);
assert.ok(scenarioFor({day:1,scenarioId:'hot-inflation'}).returns.equity<0);
assert.deepEqual(scenarioFor({day:2,seed:'test'}),scenarioFor({day:2,seed:'test'}));
for(const input of [{day:0},{day:1.5},{day:366},{day:1,scenarioId:'oops'},{day:1,previousRegime:'oops'}])assert.throws(()=>scenarioFor(input));
assert.throws(()=>assetReturns({...zero,ratesBps:Infinity}));
assert.equal(validateWeights({equity:100,bonds:1,property:0,cash:0}),false);
const people=[{id:'a'},{id:'b'}];let m=initialMarket(people);m.allocations.a={...presets.cash};m.allocations.b={...presets.growth};
const e=scenarioFor({day:1,scenarioId:'earnings-miss'});
assert.throws(()=>applyMarketDay(m,people,{a:100,b:100},e));
m.locked=true;m.lockedWeights=structuredClone(m.allocations);const old=structuredClone(m);m=applyMarketDay(m,people,{a:100,b:100},e);
assert.deepEqual(old.history,[]);close(m.pnl.a,.01);assert.ok(m.pnl.b<0);close(m.history[0].outcomes.a.closing,100.01);
close(Object.values(m.history[0].outcomes.b.byAsset).reduce((a,b)=>a+b,0),m.pnl.b);
assert.equal(m.locked,false);assert.equal(m.history.length,1);
const prior=m.pnl.a;m.locked=true;m.lockedWeights=structuredClone(m.allocations);m=applyMarketDay(m,people,{a:200,b:100},scenarioFor({day:2,scenarioId:'quiet'}));close(m.pnl.a-prior,(200+prior)*.0001);
m.frozen=true;assert.throws(()=>applyMarketDay(m,people,{a:200,b:100},e));
const all=catalog();assert.equal(all.scenarioCount,22);assert.equal(assets.length,8);
console.log('PASS: 22 scenarios, directional shocks, bond duration, deterministic regime draws, input bounds, locked allocations, cash carry, asset attribution, contribution timing and frozen funds');
